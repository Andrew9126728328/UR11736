//  HAL_GPIO_WritePin(GPIOA, AMP_MUTE_Pin, GPIO_PIN_SET);
  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(USART3_TE_GPIO_Port, USART3_TE_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(USART2_TE_GPIO_Port, USART2_TE_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pins : PEPin PEPin PEPin PEPin */
  GPIO_InitStruct.Pin = PE2_LED_RED_Pin|PE3_LED_GREEN_Pin|ETH_RST_Pin|PE1_CSEE_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
